"""Pure logic: parsing, slugging, markdown rendering. No I/O."""
from __future__ import annotations

import json
import re
from dataclasses import dataclass, field

def slugify(s: str, maxlen: int = 50) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")
    return (s[:maxlen].rstrip("-")) or "monologue"


@dataclass
class Analysis:
    title: str
    cleaned: str
    summary: str
    action_items: list[str]
    tags: list[str] = field(default_factory=list)


def extract_json(raw: str) -> dict:
    """Pull the first JSON object out of an LLM reply (handles ``` fences / prose)."""
    m = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", raw, re.S)
    if m:
        return json.loads(m.group(1))
    start = raw.find("{")
    if start < 0:
        raise ValueError("no JSON object in LLM output")
    depth = 0
    for i, ch in enumerate(raw[start:], start):
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                return json.loads(raw[start:i + 1])
    raise ValueError("unterminated JSON in LLM output")


def parse_analysis(raw: str) -> Analysis:
    d = extract_json(raw)
    items = d.get("action_items") or []
    items = [str(i).strip() for i in items if str(i).strip()]
    return Analysis(
        title=str(d.get("title") or "Monologue").strip(),
        cleaned=str(d.get("cleaned") or "").strip(),
        summary=str(d.get("summary") or "").strip(),
        action_items=items,
        tags=[slugify(t, 30) for t in (d.get("tags") or [])][:5],
    )


def render_page(a: Analysis, raw_transcript: str, date: str, audio_name: str) -> str:
    items = "\n".join(f"- [ ] {i}" for i in a.action_items) or "_None._"
    return f"""# {a.title}

*Monologue recorded {date} · source `{audio_name}` · generated by omi-monologue-pipeline*

## Summary
{a.summary}

## Action items
{items}

## Cleaned transcript
{a.cleaned}

<details><summary>Raw transcript</summary>

{raw_transcript}

</details>
"""
